package com.reelforge.core.designsystem

import androidx.compose.ui.unit.dp

/**
 * Spacing scale. Screens use these names instead of raw `.dp` values so vertical
 * rhythm stays consistent and can be retuned globally.
 */
object ReelforgeSpacing {
    val xs = 4.dp
    val sm = 8.dp
    val md = 16.dp
    val lg = 24.dp
    val xl = 32.dp
}
